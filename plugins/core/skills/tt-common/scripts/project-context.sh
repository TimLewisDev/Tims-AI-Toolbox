#!/usr/bin/env bash
# project-context.sh: create and inspect a small, machine-local project profile.
set -u

usage() {
	cat >&2 <<'EOF'
usage: project-context.sh init <repo>
       project-context.sh refresh <repo>
       project-context.sh status <repo>

init/refresh inspect repository metadata, write a cached profile and index, and
print their paths. status reports whether the cached inputs are unchanged.
The cache is outside the repository under ~/.claude/tt-projects.
EOF
	exit 2
}

[ $# -eq 2 ] || usage
cmd=$1
repo=$(cd "$2" 2>/dev/null && pwd -P) || { echo "project-context: no such repository: $2" >&2; exit 2; }
common=$(cd "$(dirname "$0")/.." && pwd -P)
knowledge="$common/scripts/knowledge.sh"

safe_key() {
	local remote name path_hash
	remote=$(git -C "$repo" config --get remote.origin.url 2>/dev/null || true)
	[ -n "$remote" ] || remote=$repo
	name=$(printf '%s' "$remote" | tr '[:upper:]' '[:lower:]' | sed 's#[^a-z0-9._-]#-#g; s/-\{2,\}/-/g; s/^-//; s/-$//')
	if command -v sha256sum >/dev/null 2>&1; then
		path_hash=$(printf '%s' "$repo" | sha256sum | awk '{print substr($1,1,12)}')
	else
		path_hash=$(printf '%s' "$repo" | shasum -a 256 | awk '{print substr($1,1,12)}')
	fi
	printf '%s-%s' "${name:-project}" "$path_hash"
}

cache_root="${TT_PROJECT_CONTEXT_DIR:-$HOME/.claude/tt-projects}"
cache="$cache_root/$(safe_key)"
profile="$cache/profile.md"
index="$cache/knowledge.tsv"
state="$cache/state.tsv"

hash_file() {
	local f=$1
	if [ -f "$f" ]; then
		if command -v sha256sum >/dev/null 2>&1; then sha256sum "$f" | awk '{print $1}'; else shasum -a 256 "$f" | awk '{print $1}'; fi
	else
		echo missing
	fi
}

tracked_inputs() {
	printf 'repo\t%s\n' "$(git -C "$repo" rev-parse --show-toplevel 2>/dev/null || printf '%s' "$repo")"
	printf 'head\t%s\n' "$(git -C "$repo" rev-parse HEAD 2>/dev/null || echo unknown)"
	printf 'branch\t%s\n' "$(git -C "$repo" branch --show-current 2>/dev/null || echo unknown)"
	for f in AGENTS.md CLAUDE.md .editorconfig package.json pyproject.toml Cargo.toml go.mod \
		Directory.Build.props Directory.Build.targets; do
		printf '%s\t%s\n' "$f" "$(hash_file "$repo/$f")"
	done
}

current_state() { tracked_inputs | sort; }

profile_fact() {
	local label=$1 value=$2 source=$3
	printf '| %s | %s | `%s` |\n' "$label" "$value" "$source"
}

write_profile() {
	local rev branch remote instructions manifests build
	rev=$(git -C "$repo" rev-parse HEAD 2>/dev/null || echo unknown)
	branch=$(git -C "$repo" branch --show-current 2>/dev/null || echo unknown)
	remote=$(git -C "$repo" config --get remote.origin.url 2>/dev/null || echo unknown)
	instructions=$(find "$repo" -maxdepth 2 -type f \( -name AGENTS.md -o -name CLAUDE.md \) \
		-not -path "$repo/.git/*" -print | sed "s#^$repo/##" | sort | paste -sd ', ' -)
	manifests=$(find "$repo" -maxdepth 2 -type f \( -name package.json -o -name pyproject.toml \
		-o -name Cargo.toml -o -name go.mod -o -name '*.csproj' -o -name ProjectVersion.txt \) \
		-not -path "$repo/.git/*" -print | sed "s#^$repo/##" | sort | paste -sd ', ' -)
	build="unknown (read repository instructions before selecting a command)"
	[ -f "$repo/package.json" ] && build="package.json scripts (inspect before running)"
	[ -f "$repo/pyproject.toml" ] && build="pyproject.toml (inspect before running)"
	[ -f "$repo/build.sh" ] && build="bash build.sh"
	cat >"$profile" <<EOF
# Project context

Generated by \`project-context.sh\`.

| Fact | Value | Source |
|---|---|---|
$(profile_fact "Repository" "$repo" "git")
$(profile_fact "Remote" "$remote" "git config")
$(profile_fact "Branch" "$branch" "git")
$(profile_fact "Revision" "$rev" "git")
$(profile_fact "Instructions" "${instructions:-none detected}" "filesystem")
$(profile_fact "Manifests" "${manifests:-none detected}" "filesystem")
$(profile_fact "Build/check hint" "$build" "filesystem")
$(profile_fact "Feature state" "Use tt-common/scripts/workflow-state.sh" "toolbox")

## Retrieval rules

- This profile routes reads; it does not replace authoritative source files.
- Validate repository facts at the stage's pinned base revision.
- Load at most two optional knowledge references initially.
- Use \`tt-common/scripts/knowledge.sh get\` before reading optional references.
EOF
}

do_init() {
	mkdir -p "$cache" || { echo "project-context: cannot create $cache" >&2; exit 2; }
	write_profile
	bash "$knowledge" index "$repo" "$index" >/dev/null
	current_state >"$state"
	printf 'Project context ready\nProfile: %s\nKnowledge index: %s\nState: %s\n' "$profile" "$index" "$state"
}

do_status() {
	[ -f "$state" ] || { echo "Project context: not initialized"; echo "Expected cache: $cache"; exit 1; }
	local old new
	old=$(cat "$state")
	new=$(current_state)
	if [ "$old" = "$new" ]; then
		echo "Project context: current"
		echo "Profile: $profile"
		echo "Knowledge index: $index"
	else
		echo "Project context: stale"
		echo "Profile: $profile"
		echo "Knowledge index: $index"
		diff -u <(printf '%s\n' "$old") <(printf '%s\n' "$new") || true
		exit 1
	fi
}

case "$cmd" in
	init|refresh) do_init ;;
	status) do_status ;;
	-h|--help) usage ;;
	*) usage ;;
esac
